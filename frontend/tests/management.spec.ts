import { test, expect } from "@playwright/test";

test("product lifecycle and inventory QC through the real admin interface", async ({ page, request }) => {
  const errors: string[] = []; page.on("pageerror", e => errors.push(e.message));
  const api = "http://localhost:5100";
  expect((await request.get(`${api}/api/admin/products`)).status()).toBe(401);
  await page.goto("/admin");
  await page.getByLabel("Username", { exact: true }).fill("admin");
  await page.getByLabel("Admin password").fill("local-browser-tests-only");
  await page.getByRole("button", { name: "Sign in" }).click();
  await page.getByRole("button", { name: "Products", exact: true }).click();
  const code = `QA-${Date.now()}`;
  await page.getByLabel("Product code", { exact: true }).fill(code);
  await page.getByLabel("Product name", { exact: true }).fill("QC browser product");
  await page.getByLabel("Series", { exact: true }).fill("Test series");
  await page.getByRole("button", { name: "Save product", exact: true }).click();
  await expect(page.getByText("Product saved.", { exact: true })).toBeVisible();
  const catalog = await page.context().newPage();
  await catalog.goto("/products");
  await catalog.getByRole("main").getByRole("link").filter({ hasText: "Test series" }).click();
  await expect(catalog.getByRole("heading", { name: "QC browser product", exact: true })).toBeVisible();
  await expect(catalog.getByText(code, { exact: true }).first()).toBeVisible();
  await catalog.close();
  await page.bringToFront();
  await page.getByRole("button", { name: "Rolls", exact: true }).click();
  await page.getByRole("combobox", { name: "Defined product", exact: true }).selectOption(code);
  await expect(page.getByLabel("Model code", { exact: true })).toHaveValue(code);
  const batch = `B-${Date.now()}`;
  await page.getByLabel("Batch", { exact: true }).fill(batch);
  await page.getByLabel("Supplier code", { exact: true }).fill("TEST");
  await page.getByRole("button", { name: "Create roll IDs" }).click();
  await expect(page.getByText("Rolls created.", { exact: true })).toBeVisible();
  const row = page.getByRole("row").filter({ hasText: batch });
  await row.getByRole("button", { name: "Manage" }).click();
  const dialog = page.getByRole("dialog", { name: "Manage inventory" });
  await dialog.getByLabel("Stock status").selectOption("shipped");
  await dialog.getByRole("button", { name: "Save inventory" }).click();
  await expect(dialog.getByRole("alert")).toHaveText("QC approval is required before release.");
  await dialog.getByLabel("Quality control").selectOption("approved");
  await dialog.getByLabel("Change note").fill("Browser quality inspection");
  await dialog.getByRole("button", { name: "Save inventory" }).click();
  await expect(dialog).toBeHidden();
  await expect(row).toContainText("shipped");
  await row.getByRole("button", { name: "Manage" }).click();
  await expect(dialog).toContainText("Browser quality inspection");
  await dialog.getByRole("button", { name: "Close inventory" }).click();
  await page.getByRole("button", { name: "Products", exact: true }).click();
  await page.getByRole("button", { name: `Edit ${code}`, exact: true }).click();
  await page.getByLabel("Availability").selectOption("true");
  await page.getByRole("button", { name: "Save product", exact: true }).click();
  await expect(page.getByRole("row").filter({ hasText: code })).toContainText("Archived");
  const publicProducts = await request.get(`${api}/api/catalog`);
  expect((await publicProducts.json()).some((p: { code: string }) => p.code === code)).toBe(false);
  await page.getByRole("button", { name: "Rolls", exact: true }).click();
  await expect(page.getByRole("combobox", { name: "Defined product", exact: true }).locator(`option[value="${code}"]`)).toHaveCount(0);
  // Server-side filters: QC + batch narrow the inventory to the one roll; a contradicting status empties it.
  await page.getByRole("button", { name: "Rolls", exact: true }).click();
  await page.getByRole("search").getByLabel("Batch contains").fill(batch);
  await page.getByRole("search").getByLabel("QC filter").selectOption("approved");
  await expect(page.getByRole("row").filter({ hasText: batch })).toHaveCount(1);
  await page.getByRole("search").getByLabel("Stock status filter").selectOption("void");
  await expect(page.getByText("No rolls match these filters.")).toBeVisible();
  await page.getByRole("button", { name: "Clear filters" }).click();
  await page.getByRole("button", { name: "Warranties", exact: true }).click();
  await page.getByRole("search").getByLabel("Search warranties").fill(`no-such-${Date.now()}`);
  await expect(page.getByText("No warranties match these filters.")).toBeVisible();
  // The session survives a reload (HttpOnly cookie) and the hash keeps the section.
  await page.reload();
  await expect(page.getByRole("heading", { name: "Registrations" })).toBeVisible();
  await page.getByRole("button", { name: "SMS", exact: true }).click();
  await expect(page.getByRole("heading", { name: "SMS gateway" })).toBeVisible();
  await expect(page.getByLabel("Code validity (minutes)")).toHaveValue(/\d+/);
  await page.getByRole("button", { name: "Customers", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Customers & vehicles" })).toBeVisible();
  await page.getByRole("button", { name: "Account", exact: true }).click();
  await expect(page.getByLabel("Current password")).toBeVisible();
  expect(errors).toEqual([]);
});
